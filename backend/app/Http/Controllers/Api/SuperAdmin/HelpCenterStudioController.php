    /**
     * Public / Authenticated Endpoint to Get Help Center Content.
     */
    public function getPublicConfig(): JsonResponse
    {
        $raw = SystemSetting::get(self::SETTING_KEY);
        if (!$raw) {
            return response()->json([
                'success' => true,
                'is_custom' => false,
                'data' => self::getDefaultConfig(),
            ]);
        }

        $config = json_decode($raw, true);
        if (!is_array($config)) {
            $config = self::getDefaultConfig();
        }

        return response()->json([
            'success' => true,
            'is_custom' => true,
            'data' => $config,
        ]);
    }

    /**
     * SuperAdmin Endpoint to Get Help Center Config for Management Studio.
     */
    public function getConfig(): JsonResponse
    {
        $raw = SystemSetting::get(self::SETTING_KEY);
        $customConfig = $raw ? json_decode($raw, true) : null;
        $defaultConfig = self::getDefaultConfig();

        $activeConfig = is_array($customConfig) ? $customConfig : $defaultConfig;

        return response()->json([
            'success' => true,
            'is_custom' => !empty($customConfig),
            'config' => $activeConfig,
            'default_config' => $defaultConfig,
            'stats' => [
                'total_categories' => count($activeConfig['categories'] ?? []),
                'total_articles' => count($activeConfig['articles'] ?? []),
                'total_faqs' => count($activeConfig['faqs'] ?? []),
            ],
        ]);
    }

    /**
     * SuperAdmin Endpoint to Update & Publish Help Center Config.
     */
    public function updateConfig(Request $request): JsonResponse
    {
        // Support both { config: { ... } } and direct payload { categories: [...], ... }
        $rawConfig = $request->has('config') && is_array($request->input('config'))
            ? $request->input('config')
            : $request->all();

        $validator = \Illuminate\Support\Facades\Validator::make(['config' => $rawConfig], [
            'config' => 'required|array',
            'config.categories' => 'required|array|min:1',
            'config.articles' => 'required|array|min:1',
            'config.faqs' => 'nullable|array',
            'config.header' => 'nullable|array',
            'config.supportContact' => 'nullable|array',
            'config.quickActionCards' => 'nullable|array',
        ]);

        if ($validator->fails()) {
            return response()->json([
                'success' => false,
                'message' => 'بيانات دليل الاستخدام غير مكتملة أو تحتوي على أخطاء.',
                'errors' => $validator->errors(),
            ], 422);
        }

        $config = $rawConfig;

        SystemSetting::set(self::SETTING_KEY, json_encode($config, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT), self::SETTING_GROUP);

        // Forensic audit log
        try {
            AuditLog::create([
                'tenant_id' => Auth::user()?->tenant_id,
                'user_id' => Auth::id(),
                'user_name' => Auth::user()?->name ?? 'SuperAdmin',
                'user_role' => 'superadmin',
                'action' => 'HELP_CENTER_CONFIG_UPDATED',
                'description' => 'تم تحديث ونشر محتوى دليل الاستخدام ومركز المساعدة بنجاح بواسطة السوبر أدمن.',
                'ip_address' => $request->ip(),
                'user_agent' => $request->userAgent(),
                'details' => [
                    'articles_count' => count($config['articles'] ?? []),
                    'categories_count' => count($config['categories'] ?? []),
                    'faqs_count' => count($config['faqs'] ?? []),
                ],
            ]);
        } catch (\Throwable $e) {
            Log::warning('Failed to log audit for help center update: ' . $e->getMessage());
        }

        return response()->json([
            'success' => true,
            'message' => 'تم حفظ ونشر دليل الاستخدام ومركز المساعدة بنجاح! 📚✨',
            'config' => $config,
        ]);
    }

    /**
     * SuperAdmin Endpoint to Reset Help Center Config to Clinical Default.
     */
    public function resetConfig(Request $request): JsonResponse
    {
        $defaultConfig = self::getDefaultConfig();
        SystemSetting::set(self::SETTING_KEY, json_encode($defaultConfig, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT), self::SETTING_GROUP);

        // Forensic audit log
        try {
            AuditLog::create([
                'tenant_id' => Auth::user()?->tenant_id,
                'user_id' => Auth::id(),
                'user_name' => Auth::user()?->name ?? 'SuperAdmin',
